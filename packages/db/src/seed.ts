// The example planets and people, after SWAPI (swapi.dev). Rows that already exist are skipped, so it can run again.
// A short-lived connection of its own, like migrateDb
export async function seedDb(env: DatabaseConfig) {
  const db = drizzle(env.DATABASE_URL);

  try {
    await db.transaction(async (tx) => {
      await tx.insert(planets).values(examplePlanets).onConflictDoNothing();
      await tx.insert(people).values(examplePeople).onConflictDoNothing();
    });
  } finally {
    await db.$client.end();
  }
}
